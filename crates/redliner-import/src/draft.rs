//! The source-agnostic draft config and its YAML rendering.
//!
//! Both front ends build a [`Draft`]; [`render`] writes it as commented YAML
//! that `redliner` loads unmodified. Output is templated text rather than a
//! serde round-trip so it can carry guidance comments.

use std::collections::BTreeMap;

use serde_json::Value;

/// Which encoder the drafted config targets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Protocol {
    Graphql,
    Rest,
}

/// A draft config, built by a front end and written by [`render`].
#[derive(Debug, Clone)]
pub struct Draft {
    /// Where the draft came from, for the header comment.
    pub source: String,
    pub target_url: String,
    pub protocol: Protocol,
    pub insecure_tls: bool,
    /// The env var holding a bearer token; only its name is ever written.
    pub bearer_env: Option<String>,
    /// Headers used to fetch the source; only their names are ever written.
    pub header_names: Vec<String>,
    pub pools: BTreeMap<String, PoolDraft>,
    pub scenarios: Vec<ScenarioDraft>,
    /// Skipped operations and hints, written as a closing comment.
    pub notes: Vec<String>,
}

/// A list pool; `todo` names the expected type when `values` are placeholders.
#[derive(Debug, Clone, PartialEq)]
pub struct PoolDraft {
    pub values: Vec<Value>,
    pub todo: Option<String>,
}

#[derive(Debug, Clone)]
pub struct ScenarioDraft {
    pub name: String,
    pub request: RequestDraft,
    /// `Some(reason)` writes the scenario commented out.
    pub commented: Option<String>,
}

/// Variable and header values are template strings (`"{{pool}}"`).
#[derive(Debug, Clone, PartialEq)]
pub enum RequestDraft {
    Graphql { query: String, variables: Vec<(String, String)> },
    Rest { method: String, path: String, headers: Vec<(String, String)>, body: Option<String> },
}

impl Draft {
    pub fn new(source: impl Into<String>, target_url: impl Into<String>, protocol: Protocol) -> Draft {
        Draft {
            source: source.into(),
            target_url: target_url.into(),
            protocol,
            insecure_tls: false,
            bearer_env: None,
            header_names: Vec::new(),
            pools: BTreeMap::new(),
            scenarios: Vec::new(),
            notes: Vec::new(),
        }
    }

    /// Sanitizes `base`, makes it unique among the pools (`_2`, `_3`, …),
    /// inserts the pool and returns its name.
    pub fn add_pool(&mut self, base: &str, pool: PoolDraft) -> String {
        let mut base = sanitize_name(base);
        if base.is_empty() {
            base = "pool".into();
        }
        let name = unique(&base, |n| self.pools.contains_key(n));
        self.pools.insert(name.clone(), pool);
        name
    }

    /// `base` if no scenario has it yet, else `base_2`, `base_3`, …
    pub fn scenario_name(&self, base: &str) -> String {
        unique(base, |n| self.scenarios.iter().any(|s| s.name == n))
    }
}

/// `base`, or the first of `base_2`, `base_3`, … that is not `taken`.
fn unique(base: &str, taken: impl Fn(&str) -> bool) -> String {
    if !taken(base) {
        return base.to_string();
    }
    (2u64..)
        .map(|i| format!("{base}_{i}"))
        .find(|n| !taken(n))
        .unwrap_or_else(|| base.to_string())
}

/// Every char outside `[A-Za-z0-9_]` becomes `_`; runs of `_` collapse;
/// leading and trailing `_` are trimmed.
pub fn sanitize_name(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        let c = if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' };
        if c == '_' && out.ends_with('_') {
            continue;
        }
        out.push(c);
    }
    out.trim_matches('_').to_string()
}

/// A JSON string literal: also a valid YAML double-quoted scalar.
fn q(s: &str) -> String {
    Value::String(s.to_string()).to_string()
}

/// Writes the draft as a commented config `redliner` loads unmodified.
pub fn render(d: &Draft) -> String {
    let mut o = format!("# Generated by redliner-import from {}.\n", d.source);
    o.push_str("# A starting point, not a finished benchmark: review the scenarios, replace the\n");
    o.push_str("# TODO pool values (or fill them with data.harvest), tune load and slos, then\n");
    o.push_str("# validate it:  redliner --config <this file> --validate\n");
    o.push_str("version: 1\n\ntarget:\n");
    o.push_str(&format!("  url: {}\n", q(&d.target_url)));
    let protocol = match d.protocol {
        Protocol::Graphql => "graphql",
        Protocol::Rest => "rest",
    };
    o.push_str(&format!("  protocol: {protocol}\n"));
    if d.insecure_tls {
        o.push_str("  insecure_tls: true\n");
    }
    if let Some(var) = &d.bearer_env {
        o.push_str(&format!("  auth:\n    type: bearer\n    token_env: {}\n", q(var)));
    }
    if !d.header_names.is_empty() {
        o.push_str(&format!(
            "  # Headers used for the import, not written here: {}\n",
            d.header_names.join(", ")
        ));
    }
    o.push_str("\nload:\n  profile: constant\n  rate: 10\n  duration: 30s\n");

    if !d.pools.is_empty() {
        o.push_str("\ndata:\n  pools:\n");
        for (name, p) in &d.pools {
            let values = Value::Array(p.values.clone());
            o.push_str(&format!("    {}: {{type: list, values: {values}}}", q(name)));
            if let Some(t) = &p.todo {
                o.push_str(&format!("  # TODO: real values ({t})"));
            }
            o.push('\n');
        }
    }

    o.push_str("\nscenarios:\n");
    let live = d.scenarios.iter().filter(|s| s.commented.is_none());
    let commented = d.scenarios.iter().filter(|s| s.commented.is_some());
    let mut blocks: Vec<String> = live.map(scenario_block).collect();
    for s in commented {
        let reason = s.commented.as_deref().unwrap_or_default();
        let mut b =
            format!("  # {reason}; delete the leading \"# \" on the lines below to include it:\n");
        for line in scenario_block(s).lines() {
            b.push_str("# ");
            b.push_str(line);
            b.push('\n');
        }
        blocks.push(b);
    }
    o.push_str(&blocks.join("\n"));

    o.push_str("\n# slos: {success_rate: 0.99, p95: 500ms}\n");
    if !d.notes.is_empty() {
        o.push_str("\n# Notes:\n");
        for n in &d.notes {
            o.push_str(&format!("#   - {n}\n"));
        }
    }
    o
}

/// One scenario as a list item under `scenarios:`.
fn scenario_block(s: &ScenarioDraft) -> String {
    let mut b = format!("  - name: {}\n    weight: 1\n    request:\n", q(&s.name));
    match &s.request {
        RequestDraft::Graphql { query, variables } => {
            b.push_str("      query: |\n");
            for line in query.lines() {
                if !line.is_empty() {
                    b.push_str("        ");
                    b.push_str(line);
                }
                b.push('\n');
            }
            if !variables.is_empty() {
                b.push_str("      variables:\n");
                for (k, v) in variables {
                    b.push_str(&format!("        {}: {}\n", q(k), q(v)));
                }
            }
        }
        RequestDraft::Rest { method, path, headers, body } => {
            b.push_str(&format!("      method: {}\n      path: {}\n", q(method), q(path)));
            if !headers.is_empty() {
                b.push_str("      headers:\n");
                for (k, v) in headers {
                    b.push_str(&format!("        {}: {}\n", q(k), q(v)));
                }
            }
            if let Some(body) = body {
                b.push_str(&format!("      body: {}\n", q(body)));
            }
        }
    }
    b
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testutil::assert_contract;
    use serde_json::json;

    const PRODUCT_QUERY: &str = "query product($id: Int!) {\n  product(id: $id) {\n    id\n  }\n}\n";

    fn gql_draft() -> Draft {
        let mut d = Draft::new("a test", "http://h/graphql", Protocol::Graphql);
        let pool = d.add_pool(
            "product_id",
            PoolDraft { values: vec![json!(1)], todo: Some("Int!".into()) },
        );
        d.scenarios.push(ScenarioDraft {
            name: "product".into(),
            request: RequestDraft::Graphql {
                query: PRODUCT_QUERY.into(),
                variables: vec![("id".into(), format!("{{{{{pool}}}}}"))],
            },
            commented: None,
        });
        d
    }

    fn rest_scenario(name: &str, commented: Option<&str>) -> ScenarioDraft {
        ScenarioDraft {
            name: name.into(),
            request: RequestDraft::Rest {
                method: "GET".into(),
                path: "/a/{{p}}?q={{p}}".into(),
                headers: vec![("X-Trace".into(), "{{p}}".into())],
                body: None,
            },
            commented: commented.map(String::from),
        }
    }

    fn rest_draft(scenarios: Vec<ScenarioDraft>) -> Draft {
        let mut d = Draft::new("a test", "http://h", Protocol::Rest);
        d.add_pool("p", PoolDraft { values: vec![json!("x")], todo: None });
        d.scenarios = scenarios;
        d
    }

    /// The lines from `first` (included or not) up to the next blank line.
    fn block(out: &str, first: &str, include_first: bool) -> Vec<String> {
        let mut it = out.lines().skip_while(|l| *l != first).peekable();
        if !include_first {
            it.next();
        }
        it.take_while(|l| !l.is_empty()).map(String::from).collect()
    }

    #[test]
    fn graphql_draft_renders_a_loadable_config() {
        let out = render(&gql_draft());
        let cfg = assert_contract(&out);
        let r = &cfg.scenarios[0].request;
        assert_eq!(r.variables["id"], json!("{{product_id}}"));
        assert_eq!(r.query, PRODUCT_QUERY);
        assert!(
            out.contains("\"product_id\": {type: list, values: [1]}  # TODO: real values (Int!)"),
            "{out}"
        );
    }

    #[test]
    fn rest_draft_renders_a_loadable_config() {
        let cfg = assert_contract(&render(&rest_draft(vec![rest_scenario("GET /a", None)])));
        let r = &cfg.scenarios[0].request;
        assert_eq!(r.method, "GET");
        assert_eq!(r.headers["X-Trace"], "{{p}}");
    }

    #[test]
    fn commented_scenario_is_the_live_block_prefixed() {
        let live = render(&rest_draft(vec![rest_scenario("GET /a", None)]));
        let live_block = block(&live, "  - name: \"GET /a\"", true);
        assert!(!live_block.is_empty(), "{live}");

        let reason = "  # POST changes state; delete the leading \"# \" on the lines below to include it:";
        let commented =
            render(&rest_draft(vec![rest_scenario("GET /a", Some("POST changes state"))]));
        assert!(commented.lines().any(|l| l == reason), "{commented}");
        let stripped: Vec<String> = block(&commented, reason, false)
            .iter()
            .map(|l| l.strip_prefix("# ").expect("every commented line starts with \"# \"").to_string())
            .collect();
        assert_eq!(stripped, live_block);

        let both = rest_draft(vec![
            rest_scenario("GET /a", None),
            rest_scenario("POST /a", Some("POST changes state")),
        ]);
        assert_eq!(assert_contract(&render(&both)).scenarios.len(), 1);
    }

    #[test]
    fn awkward_strings_round_trip_exactly() {
        let url = "http://h:8080/x?y=1#frag";
        let name = "GET /a: #1";
        let path = "/a?q={{p}}&b=x y: #z";
        let body = "{\"q\":\"a \\\"b\\\"\\nc\"}";
        let mut d = Draft::new("a test", url, Protocol::Rest);
        d.add_pool("p", PoolDraft { values: vec![json!("v")], todo: None });
        d.scenarios.push(ScenarioDraft {
            name: name.into(),
            request: RequestDraft::Rest {
                method: "POST".into(),
                path: path.into(),
                headers: vec![],
                body: Some(body.into()),
            },
            commented: None,
        });
        let cfg = assert_contract(&render(&d));
        assert_eq!(cfg.target.url, url);
        assert_eq!(cfg.scenarios[0].name, name);
        assert_eq!(cfg.scenarios[0].request.path, path);
        assert_eq!(cfg.scenarios[0].request.body, body);
    }

    #[test]
    fn nested_pool_values_round_trip() {
        let values = vec![json!({"a": [1, "x"], "b": {"c": null}}), json!(true), json!(1.5), json!([])];
        let mut d = rest_draft(vec![rest_scenario("GET /a", None)]);
        d.add_pool("v", PoolDraft { values: values.clone(), todo: None });
        assert_eq!(assert_contract(&render(&d)).data.pools["v"].values, values);
    }

    #[test]
    fn render_is_deterministic() {
        let mut d = rest_draft(vec![rest_scenario("GET /a", None)]);
        d.add_pool("b", PoolDraft { values: vec![json!(1)], todo: None });
        d.add_pool("a", PoolDraft { values: vec![json!(2)], todo: None });
        let (one, two) = (render(&d), render(&d));
        assert_eq!(one, two);
        let (a, b) = (one.find("\"a\": {").unwrap(), one.find("\"b\": {").unwrap());
        assert!(a < b, "{one}");
    }

    #[test]
    fn target_options_render() {
        let mut d = rest_draft(vec![rest_scenario("GET /a", None)]);
        d.insecure_tls = true;
        d.bearer_env = Some("BENCH_TOKEN".into());
        d.header_names = vec!["X-Api-Key".into(), "X-Team".into()];
        let out = render(&d);
        assert!(out.contains("token_env: \"BENCH_TOKEN\""), "{out}");
        assert!(
            out.lines()
                .any(|l| l == "  # Headers used for the import, not written here: X-Api-Key, X-Team"),
            "{out}"
        );
        let cfg = assert_contract(&out);
        assert!(cfg.target.insecure_tls);
        assert_eq!(cfg.target.auth.auth_type, "bearer");
    }

    #[test]
    fn names_are_sanitized_and_unique() {
        assert_eq!(sanitize_name("GET /pets/{petId}/photos_petId"), "GET_pets_petId_photos_petId");
        let mut d = Draft::new("t", "http://h", Protocol::Rest);
        let pool = || PoolDraft { values: vec![json!(1)], todo: None };
        assert_eq!(d.add_pool("a-b", pool()), "a_b");
        assert_eq!(d.add_pool("a_b", pool()), "a_b_2");
        assert_eq!(d.add_pool("a b", pool()), "a_b_3");
        // A name that sanitizes to nothing still gets a usable pool name.
        assert_eq!(d.add_pool("{}", pool()), "pool");
        d.scenarios.push(rest_scenario("x", None));
        assert_eq!(d.scenario_name("x"), "x_2");
        assert_eq!(d.scenario_name("y"), "y");
    }
}
